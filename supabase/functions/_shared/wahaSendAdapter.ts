/**
 * Shared WAHA outbound dispatch (persist + send + persist).
 *
 * `waha-send/index.ts` (manual send, via caller JWT) and
 * `scheduled-send-worker/index.ts` (server-side scheduled dispatch, via
 * service_role) both need the exact same steps for a `waha` account:
 * resolve session/server, insert the queued `messages` row, call the WAHA
 * REST API, flip the row to sent/failed, touch the conversation, audit.
 *
 * Extracted here so the two callers never drift. The scheduled-send path
 * never had this at all (it always went through the generic
 * `buildWhatsAppEngine`, which has no `waha` branch by isolation design —
 * PRDs 112/113), so every scheduled send from a WAHA conversation failed
 * with `VALIDATION_ERROR: Engine WhatsApp desconhecido: waha` (found
 * 2026-07-12 via a real failed `scheduled_sends` row).
 *
 * Edge-runtime module (Deno): esm.sh + service_role. NOT part of the
 * src/providers/whatsapp mirror (that tree is wiped/regenerated by the sync
 * script), so it lives directly under _shared/ — same as
 * whatsappSendAdapter.ts.
 */

